//! TypeScript types of the content, for the frontend.

use crate::schema::{ASSET, ColumnKind, Component, FieldKind, Schema, USER};

const HEADER: &str = "// Generated by `zipp types`, don't edit.

export type EntryRef = {
	id: number;
	section: string;
	type: string;
	title: string;
	slug: string;
	uri: string | null;
};

// required fields only have to be there in a published entry, an
// unpublished one has its draft fields `D`
export type Entry<T extends string, F, D> = {
	id: number;
	section: string;
	type: T;
	site: string;
	title: string;
	slug: string;
	uri: string | null;
	parentId: number | null;
	createdAt: number;
	updatedAt: number;
	authorId: number | null;
} & ({ published: true; fields: F } | { published: false; fields: D });

export type Block<T extends string, F> = { id: string; type: T; fields: F };

export type NavItem = {
	type: 'entry' | 'url' | 'email' | 'phone' | 'asset';
	value: string | number;
	label?: string;
	newTab?: boolean;
	download?: boolean;
	anchor?: string;
	children?: NavItem[];
};
";

pub fn generate(schema: &Schema) -> String {
	let mut out = HEADER.to_string();

	for comp in &schema.components {
		let name = pascal(&comp.handle);
		out += &format!(
			"\nexport type {name}Fields = {};\n",
			fields(schema, comp, false)
		);
		// the asset and user fields are no block and always required,
		// `AssetFields` is enough
		if comp.handle == ASSET || comp.handle == USER {
			continue;
		}

		// a draft or an unpublished entry may lack the required fields,
		// in its blocks and groups too
		out += &format!(
			"export type {name}DraftFields = {};\n",
			fields(schema, comp, true)
		);
		out += &if comp.entry {
			format!(
				"export type {name} = \
				 Entry<'{}', {name}Fields, {name}DraftFields>;\n",
				comp.handle
			)
		} else {
			format!(
				"export type {name}Block = Block<'{}', {name}Fields>;\n\
				 export type {name}DraftBlock = \
				 Block<'{}', {name}DraftFields>;\n",
				comp.handle, comp.handle
			)
		};
	}

	let entries: Vec<_> = schema
		.components
		.iter()
		.filter(|c| c.entry)
		.map(|c| pascal(&c.handle))
		.collect();
	if !entries.is_empty() {
		out += &format!("\nexport type AnyEntry = {};\n", entries.join(" | "));
	}

	out
}

/// The value of a link field and of a link in a table.
const LINK: &str = "{ type: 'entry' | 'url' | 'email' | 'phone' | 'asset'; \
	value: string | number; label?: string; newTab?: boolean; \
	download?: boolean; anchor?: string }";

/// The fields of a component, with `draft` all optional and its blocks
/// and groups as drafts.
fn fields(schema: &Schema, comp: &Component, draft: bool) -> String {
	// notes have no value
	let fields: Vec<_> =
		comp.fields.iter().filter(|f| f.kind.has_value()).collect();
	if fields.is_empty() {
		return "Record<string, never>".into();
	}

	let mut out = "{\n".to_string();
	for f in fields {
		// a field hidden by its condition needn't be filled to publish,
		// nor what is inside it
		let draft = draft || !comp.conditions_of(&f.handle).is_empty();
		let suffix = if draft { "Draft" } else { "" };
		let ty = match &f.kind {
			FieldKind::Text { .. } | FieldKind::Email => "string".into(),
			// `2026-11-14`, with a time `2026-11-14T20:00`
			FieldKind::Date { .. } => "string".into(),
			FieldKind::Number { .. } => "number".into(),
			FieldKind::Boolean => "boolean".into(),
			FieldKind::Relation { .. } | FieldKind::Assets { .. } => {
				"number[]".into()
			}
			FieldKind::Markdown => "string".into(),
			FieldKind::Texts { .. } => "Record<string, string>".into(),
			FieldKind::Checkboxes { options } => format!(
				"({})[]",
				options
					.iter()
					.map(|o| format!("{:?}", o.value))
					.collect::<Vec<_>>()
					.join(" | ")
			),
			FieldKind::Table { columns } => format!(
				"{{ {} }}[]",
				columns
					.iter()
					.map(|c| format!("{}?: {}", c.handle, cell_type(&c.kind)))
					.collect::<Vec<_>>()
					.join("; ")
			),
			FieldKind::Navigation { .. } => "NavItem[]".into(),
			FieldKind::Dropdown { options } => options
				.iter()
				.map(|o| format!("{:?}", o.value))
				.collect::<Vec<_>>()
				.join(" | "),
			FieldKind::ButtonGroup { options } => options
				.iter()
				.map(|o| format!("{:?}", o.value))
				.collect::<Vec<_>>()
				.join(" | "),
			FieldKind::Group { component } => {
				format!("{}{suffix}Fields", pascal(component))
			}
			FieldKind::RichText { .. } => {
				"{ type: 'doc'; content: unknown[] }".into()
			}
			FieldKind::Link { .. } => LINK.into(),
			FieldKind::Blocks { types, .. } => {
				let blocks: Vec<_> = types
					.iter()
					.map(|t| format!("{}{suffix}Block", pascal(t)))
					.collect();
				format!("({})[]", blocks.join(" | "))
			}
			FieldKind::Custom { ty, .. } => schema
				.field_types
				.get(ty)
				.map(|t| t.typescript())
				.unwrap_or_else(|| "unknown".into()),
			FieldKind::Note { .. } => unreachable!(),
		};
		let opt = if f.required && !draft { "" } else { "?" };
		out += &format!("\t{}{opt}: {ty};\n", f.handle);
	}
	out + "}"
}

/// The type of a cell of a table, like the field of its kind.
fn cell_type(kind: &ColumnKind) -> String {
	match kind {
		ColumnKind::Number { .. } => "number".into(),
		ColumnKind::Boolean => "boolean".into(),
		ColumnKind::Dropdown { options } => options
			.iter()
			.map(|o| format!("{:?}", o.value))
			.collect::<Vec<_>>()
			.join(" | "),
		ColumnKind::Link { .. } => LINK.into(),
		ColumnKind::Text
		| ColumnKind::Url
		| ColumnKind::Email
		| ColumnKind::Date => "string".into(),
	}
}

fn pascal(handle: &str) -> String {
	let mut c = handle.chars();
	match c.next() {
		Some(first) => first.to_ascii_uppercase().to_string() + c.as_str(),
		None => String::new(),
	}
}

#[cfg(test)]
mod tests {
	use super::*;
	use crate::fixtures::site;
	use crate::schema::{Condition, Field};

	#[test]
	fn generates_types() {
		let ts = generate(&site());
		assert!(ts.contains(
			"export type Page = Entry<'page', PageFields, PageDraftFields>;"
		));
		assert!(ts.contains("\tbody?: (TextBlock | ButtonBlock)[];"));
		assert!(ts.contains("\tlabel: string;"));
		assert!(ts.contains("export type AnyEntry = Page | Event;"));
		// a note has no value
		assert!(!ts.contains("howto"));
	}

	#[test]
	fn drafts_may_lack_required_fields() {
		let ts = generate(&site());
		// only a published entry has its required fields
		assert!(ts.contains(
			"({ published: true; fields: F } | \
			 { published: false; fields: D })"
		));
		assert!(ts.contains("export type ButtonFields = {\n\tlabel: string;"));
		assert!(
			ts.contains("export type ButtonDraftFields = {\n\tlabel?: string;")
		);
		assert!(ts.contains(
			"export type ButtonDraftBlock = Block<'button', ButtonDraftFields>;"
		));
		// blocks of a draft are drafts too
		assert!(ts.contains("\tbody?: (TextDraftBlock | ButtonDraftBlock)[];"));
		assert!(ts.contains("\tseo?: SeoDraftFields;"));
	}

	#[test]
	fn conditional_fields_are_optional() {
		// hidden by its condition, a required field needn't be filled
		let ts = generate(
			&site().asset_fields([
				Field::boolean("credited"),
				Field::text("credit")
					.required()
					.when(Condition::on("credited")),
			]),
		);
		assert!(ts.contains("\tcredit?: string;"));
	}

	#[test]
	fn asset_fields_are_no_block() {
		let ts = generate(&site().asset_fields([Field::text("credit")]));
		assert!(
			ts.contains("export type AssetFields = {\n\tcredit?: string;\n}")
		);
		assert!(!ts.contains("AssetBlock"));
	}
}
