//! TypeScript types of the content, for the frontend.

use crate::schema::{Component, FieldKind, Schema};

const HEADER: &str = "// Generated by `zipp types`, don't edit.

export type EntryRef = {
	id: number;
	section: string;
	type: string;
	title: string;
	slug: string;
	uri: string | null;
};

export type Entry<T extends string, F> = {
	id: number;
	section: string;
	type: T;
	site: string;
	title: string;
	slug: string;
	uri: string | null;
	published: boolean;
	parentId: number | null;
	fields: F;
	createdAt: number;
	updatedAt: number;
};

export type Block<T extends string, F> = { id: string; type: T; fields: F };

export type NavItem = {
	type: 'entry' | 'url' | 'email' | 'phone' | 'asset';
	value: string | number;
	label?: string;
	newTab?: boolean;
	download?: boolean;
	anchor?: string;
	children?: NavItem[];
};
";

pub fn generate(schema: &Schema) -> String {
	let mut out = HEADER.to_string();

	for comp in &schema.components {
		let name = pascal(&comp.handle);
		out += &format!(
			"\nexport type {name}Fields = {};\n",
			fields(schema, comp)
		);
		out += &if comp.entry {
			format!(
				"export type {name} = Entry<'{}', {name}Fields>;\n",
				comp.handle
			)
		} else {
			format!(
				"export type {name}Block = Block<'{}', {name}Fields>;\n",
				comp.handle
			)
		};
	}

	let entries: Vec<_> = schema
		.components
		.iter()
		.filter(|c| c.entry)
		.map(|c| pascal(&c.handle))
		.collect();
	if !entries.is_empty() {
		out += &format!("\nexport type AnyEntry = {};\n", entries.join(" | "));
	}

	out
}

fn fields(schema: &Schema, comp: &Component) -> String {
	if comp.fields.is_empty() {
		return "Record<string, never>".into();
	}

	let mut out = "{\n".to_string();
	for f in &comp.fields {
		let ty = match &f.kind {
			FieldKind::Text { .. } => "string".into(),
			FieldKind::Number { .. } => "number".into(),
			FieldKind::Boolean => "boolean".into(),
			FieldKind::Relation { .. } | FieldKind::Assets { .. } => {
				"number[]".into()
			}
			FieldKind::Markdown => "string".into(),
			FieldKind::Texts { .. } => "Record<string, string>".into(),
			FieldKind::Checkboxes { options } => format!(
				"({})[]",
				options
					.iter()
					.map(|o| format!("{:?}", o.value))
					.collect::<Vec<_>>()
					.join(" | ")
			),
			FieldKind::Table { columns } => format!(
				"{{ {} }}[]",
				columns
					.iter()
					.map(|c| format!("{}?: string", c.handle))
					.collect::<Vec<_>>()
					.join("; ")
			),
			FieldKind::Navigation { .. } => "NavItem[]".into(),
			FieldKind::Dropdown { options } => options
				.iter()
				.map(|o| format!("{:?}", o.value))
				.collect::<Vec<_>>()
				.join(" | "),
			FieldKind::Group { component } => {
				format!("{}Fields", pascal(component))
			}
			FieldKind::RichText { .. } => {
				"{ type: 'doc'; content: unknown[] }".into()
			}
			FieldKind::Link { .. } => {
				"{ type: 'entry' | 'url' | 'email' | 'phone' | 'asset'; \
				value: string | number; label?: string; newTab?: boolean; \
				download?: boolean; anchor?: string }"
					.into()
			}
			FieldKind::Blocks { types, .. } => {
				let blocks: Vec<_> = types
					.iter()
					.map(|t| format!("{}Block", pascal(t)))
					.collect();
				format!("({})[]", blocks.join(" | "))
			}
			FieldKind::Custom { ty, .. } => schema
				.field_types
				.get(ty)
				.map(|t| t.typescript())
				.unwrap_or_else(|| "unknown".into()),
		};
		let opt = if f.required { "" } else { "?" };
		out += &format!("\t{}{opt}: {ty};\n", f.handle);
	}
	out + "}"
}

fn pascal(handle: &str) -> String {
	let mut c = handle.chars();
	match c.next() {
		Some(first) => first.to_ascii_uppercase().to_string() + c.as_str(),
		None => String::new(),
	}
}

#[cfg(test)]
mod tests {
	use super::*;
	use crate::schema::tests::site;

	#[test]
	fn generates_types() {
		let ts = generate(&site());
		assert!(ts.contains("export type Page = Entry<'page', PageFields>;"));
		assert!(ts.contains("\tbody?: (TextBlock | ButtonBlock)[];"));
		assert!(ts.contains("\tlabel: string;"));
		assert!(ts.contains("export type AnyEntry = Page | Event;"));
	}
}
